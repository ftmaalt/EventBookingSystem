CREATE TABLE sessions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    start_time       TIMESTAMP NOT NULL,
    end_time         TIMESTAMP NOT NULL,
    capacity         INTEGER NOT NULL,
    spots_left       INTEGER NOT NULL,
    status           VARCHAR(255) NOT NULL,
    version          BIGINT,
    created_at       TIMESTAMP,
    updated_at       TIMESTAMP,
    -- ids and snapshots taken from catalog-service when the session is created
    activity_id      BIGINT NOT NULL,
    activity_title   VARCHAR(150) NOT NULL,
    provider_id      BIGINT NOT NULL,
    price_per_person NUMERIC(10,3) NOT NULL
);

CREATE TABLE bookings (
    booking_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participants        INTEGER NOT NULL,
    booking_type        VARCHAR(255) NOT NULL,
    subtotal            NUMERIC(10,3) NOT NULL,
    discount_percent    NUMERIC(5,2),
    total_price         NUMERIC(10,3) NOT NULL,
    status              VARCHAR(255) NOT NULL,
    payment_status      VARCHAR(255) NOT NULL,
    cancellation_reason VARCHAR(255),
    created_at          TIMESTAMP,
    updated_at          TIMESTAMP,
    last_reminder_stage VARCHAR(20),
    created_by          VARCHAR(150),
    updated_by          VARCHAR(150),
    user_id             BIGINT NOT NULL,      -- owned by auth-service (no FK across schemas)
    user_email          VARCHAR(150) NOT NULL, -- snapshot, used later by notifications
    session_id          BIGINT NOT NULL REFERENCES sessions(id)
);

CREATE TABLE waitlist (
    entry_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status     VARCHAR(255) NOT NULL,
    joined_at  TIMESTAMP NOT NULL,
    user_id    BIGINT NOT NULL,
    user_email VARCHAR(150) NOT NULL,
    session_id BIGINT NOT NULL REFERENCES sessions(id)
);

CREATE INDEX idx_sessions_activity ON sessions(activity_id);
CREATE INDEX idx_bookings_user ON bookings(user_id);
CREATE INDEX idx_bookings_session ON bookings(session_id);
CREATE INDEX idx_waitlist_session ON waitlist(session_id);

-- last line of defence for concurrency: one live booking / one waiting entry per user per session
CREATE UNIQUE INDEX ux_bookings_active ON bookings(user_id, session_id) WHERE status IN ('CONFIRMED', 'PENDING_PAYMENT');
CREATE UNIQUE INDEX ux_waitlist_waiting ON waitlist(user_id, session_id) WHERE status = 'WAITING';

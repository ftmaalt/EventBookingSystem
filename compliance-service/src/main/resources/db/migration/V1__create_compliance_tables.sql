CREATE TABLE violations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type        VARCHAR(255) NOT NULL,
    excused     BOOLEAN NOT NULL,
    note        VARCHAR(500),
    created_at  TIMESTAMP,
    updated_at  TIMESTAMP,
    booking_id  BIGINT,           -- owned by booking-service (no FK across schemas)
    session_id  BIGINT,           -- owned by booking-service
    user_id     BIGINT NOT NULL,  -- the offender, owned by auth-service
    reported_by BIGINT NOT NULL   -- the reporter, owned by auth-service
);

CREATE TABLE penalties (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strike_number SMALLINT NOT NULL,
    amount        NUMERIC(10,3),
    status        VARCHAR(255) NOT NULL,
    created_at    TIMESTAMP,
    paid_at       TIMESTAMP,
    user_id       BIGINT NOT NULL
);

-- strike bookkeeping that used to live on the users table
CREATE TABLE violation_counters (
    user_id                BIGINT PRIMARY KEY,
    consecutive_violations SMALLINT NOT NULL DEFAULT 0,
    strike_count           SMALLINT NOT NULL DEFAULT 0,
    updated_at             TIMESTAMP
);

CREATE INDEX idx_violations_user ON violations(user_id);
CREATE INDEX idx_penalties_user ON penalties(user_id);

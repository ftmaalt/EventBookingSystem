CREATE TABLE provider_applications (
                                       application_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       business_name       VARCHAR(150) NOT NULL,
                                       contact_name        VARCHAR(100) NOT NULL,
                                       email               VARCHAR(150) NOT NULL,
                                       phone               VARCHAR(20)  NOT NULL,
                                       city                VARCHAR(80)  NOT NULL,
                                       description         TEXT,
                                       proposed_activities TEXT         NOT NULL,
                                       status              VARCHAR(255) NOT NULL,
                                       review_note         VARCHAR(500),
                                       reviewed_at         TIMESTAMP,
                                       created_at          TIMESTAMP,
                                       reviewed_by         BIGINT REFERENCES users(id),
                                       created_user_id     BIGINT NOT NULL REFERENCES users(id)
);

CREATE TABLE provider_profiles (
                                   provider_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   business_name VARCHAR(150) NOT NULL,
                                   description   TEXT,
                                   phone         VARCHAR(20),
                                   created_at    TIMESTAMP,
                                   updated_at    TIMESTAMP,
                                   user_id       BIGINT NOT NULL UNIQUE REFERENCES users(id)
);